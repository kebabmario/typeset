import type { FontCategory, FontFamily } from "./types";

/** Every 100 from min to max, inclusive. */
const range = (min: number, max: number) =>
  Array.from({ length: (max - min) / 100 + 1 }, (_, i) => min + i * 100);

type Entry = [family: string, weights: number[]];

const group = (category: FontCategory, entries: Entry[]): FontFamily[] =>
  entries.map(([family, weights]) => ({ family, category, weights }));

